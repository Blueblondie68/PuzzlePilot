function makeQuestion(id, question, answers, correctAnswer, difficulty) {
    const artistTags = performerTags[correctAnswer];
    const recording = recordingTags[id];
    if (!artistTags || !recording) {
        throw new Error(`Missing tagging information for ${id}`);
    }

    const year = recording[0];
    const decade = `${Math.floor(year / 10) * 10}s`;
    const titleMatch = question.match(/'(.+)'/);
    if (!titleMatch) {
        throw new Error(`Missing song title for ${id}`);
    }

    return {
        id,
        category: "Music",
        difficulty,
        question,
        answers,
        correctAnswer,
        tags: [...new Set([
            "music", "songs", "recordings", "singles",
            decade, `${decade} music`, `${year} releases`,
            titleMatch[1].toLowerCase(), correctAnswer.toLowerCase(),
            ...artistTags, ...recording.slice(1)
        ])],
        dailyEligible: true
    };
}

